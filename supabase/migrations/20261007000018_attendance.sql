-- 근태·연차 (예전 대시보드에서 옮김)
--   * 출근·퇴근 버튼, 지각·조퇴 자동 판정 (기본근무 / 시차근무, 반차, 직퇴·생일·프로모션 조기퇴근)
--   * 연차·반차·경조휴가·포상휴가 신청 → 1차 승인 → 최종 승인 (대표·팀장). 승인된 연차 취소도 같은 2단계
--   * 기타 근태·미팅·직퇴·조기퇴근 신청 → 승인, 근태 수정 요청 → 처리
--   * 연차 잔액(부여+조정−사용), 1년 미만 월차 자동 부여, 공휴일, 근무시간 설정
--   * 보기: 직원은 본인 것만, 대표·팀장은 전체. 승인된 휴가·공휴일·근태 예외는 달력에서 모두에게 보임
--   * 예전 대시보드 기록은 import_legacy_attendance로 옮김 (여러 번 눌러도 중복 없음, 예전 번호 legacy_id)

