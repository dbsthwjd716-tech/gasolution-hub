-- 메타: 담당 배정 기간 기준 담당자별 일 광고비 (예전 v_meta_employee_daily_spend 와 같은 계산)
create view public.ads_meta_manager_daily with (security_invoker = true) as
select d.stat_date, ma.id meta_account_id, ma.external_account_id, ma.account_name, ma.advertiser_id, adv.name advertiser_name,
       paa.manager, d.spend, coalesce(paa.allocation_rate, 1) allocation_rate,
       round(d.spend * coalesce(paa.allocation_rate, 1), 2) attributed_spend, d.currency
  from public.ads_meta_spend_daily d
  join public.ads_meta_accounts ma on ma.id = d.meta_account_id
  join public.ads_perf_accounts pa on pa.id = ma.perf_account_id and pa.platform = 'META'
  left join public.ads_perf_assignments paa on paa.perf_account_id = pa.id and paa.valid_from <= d.stat_date and (paa.valid_to is null or paa.valid_to >= d.stat_date)
  left join public.ads_advertisers adv on adv.id = ma.advertiser_id
 where ma.is_active;

-- 읽기 권한: 재직 직원 (비밀값 상태 표는 대표·팀장만)
do $$
declare t text;
begin
  foreach t in array array['ads_advertisers','ads_groups','ads_group_members','ads_group_handover_history','ads_manager_keys',
    'ads_perf_accounts','ads_perf_assignments','ads_meta_accounts','ads_meta_spend_daily','ads_bizmoney_snapshots','ads_sync_runs',
    'ads_searchad_daily','ads_searchad_status','ads_transferred_daily','ads_api_credentials'] loop
    execute format('alter table public.%I enable row level security', t);
    if t = 'ads_api_credentials' then
      execute format('create policy %I on public.%I for select to authenticated using (public.is_manager())', t || '_select', t);
    else
      execute format('create policy %I on public.%I for select to authenticated using (public.my_staff_id() is not null)', t || '_select', t);
    end if;
    execute format('grant select on public.%I to authenticated', t);
    execute format('create trigger zz_preview_block before insert or update or delete on public.%I for each statement execute function public.preview_block()', t);
  end loop;
end $$;
grant select on public.ads_meta_manager_daily to authenticated;
