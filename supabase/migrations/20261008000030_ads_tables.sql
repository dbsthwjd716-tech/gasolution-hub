-- 광고 수집 이전 1단계: 예전 네이버 대시보드의 광고 표를 통합 DB로 (같은 id 유지)
--   읽기: 재직 직원 (화면에서 담당 범위로 거름) · 쓰기: 대표·팀장 화면 함수 또는 수집기(토큰)만
--   비밀값(API 키)은 표에 두지 않고 금고(vault)에 둠 → ads_api_credentials 에는 금고 id와 끝 4자리만

create table public.ads_advertisers (
  id                bigint generated by default as identity primary key,
  name              text,
  customer_id       text unique,
  manager           text,
  credential_group  text,
  mapped_at         date,
  adcost_source     text not null default 'auto' check (adcost_source in ('auto','naver_api','transferred')),
  transferred_at    date,
  gfa_ad_account_no bigint,
  notes             text,
  client_id         uuid references public.clients(id) on delete set null,
  created_at        timestamptz not null default now()
);
comment on table public.ads_advertisers is '광고 계정(네이버 검색광고·GFA·메타 껍데기). 예전 advertisers 와 같은 id';

create table public.ads_groups (
  id              bigint generated by default as identity primary key,
